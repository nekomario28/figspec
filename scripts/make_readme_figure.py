#!/usr/bin/env python3
"""Write the README's figure: the storyboard of a figure with a real finding.

The claim on the front page is "inspect the declaration, then look at what it
meant" — so the figure is the product of that: a declared bar chart whose axis
starts at 25, and the same chart with the finding boxed and numbered.

Deterministic by construction: figspec renumbers the engine's clip ids, so two
renders of one model are byte-identical, and the test that pins this asset is an
equality check rather than a tolerance.

    python scripts/make_readme_figure.py     # writes docs/assets/storyboard.svg
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))

import figspec  # noqa: E402

MODEL = ROOT / "examples" / "storyboard_demo.json"
OUT = ROOT / "docs" / "assets" / "storyboard.svg"
CAPTION = (
    "<!-- Generated by scripts/make_readme_figure.py from "
    "examples/storyboard_demo.json: a test fails if this file and the renderer "
    "disagree. -->\n"
)


def render() -> str:
    model = figspec.load(MODEL)
    problems = figspec.inspect(model)
    assert problems, "the demo must have something to point at"
    return CAPTION + figspec.storyboard_svg(model)


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
